"""Holonomy decomposition of a finite transformation semigroup.

The holonomy method of Zeiger :cite:`Zeiger1967`, streamlined by Eilenberg
:cite:`Eilenberg1976`, emulates ``(Q, S)`` by a cascade (iterated wreath
product) whose components are permutation groups -- the *holonomy groups* --
each augmented with constant maps (resets). This module follows the
constructive presentation of Egri-Nagy & Nehaniv :cite:`EgriNagyNehaniv2015`:

1. The *extended image set* ``I`` is ``{Q · s : s ∈ S¹}`` together with all
   singletons.
2. Two sets are equivalent when each is the image of the other; the classes
   are the strongly connected components of ``S`` acting on ``I``.
   *Subduction* ``P ≤ R`` (``P ⊆ R · s`` for some ``s ∈ S¹``) orders the
   classes, and the *height* of a set is the length of the longest strict
   subduction chain of non-singletons ending at it. The cascade has one level
   per height ``1, ..., h(Q)``; levels are numbered by *depth*
   ``d = h(Q) - h + 1`` so the top level is depth 1.
3. The *tiles* of a set are its maximal proper subsets in ``I``. The holonomy
   group of a class representative ``R`` is the permutation group its
   setwise stabilizer induces on its tiles. It is generated by round trips
   ``R -> P -s-> P' -> R`` through the class (Schreier generators), so it is
   computed from the generators of ``S`` alone, without enumerating ``S``.

States are lifted to maximal tile chains ``Q = P_0 ⊃ P_1 ⊃ ... ⊃ {x}``; the
tile below ``P_i`` sits at level ``d(P_i)`` and is recorded relative to the
representative of ``P_i``. Those relative tiles are the cascade coordinates.
"""

from __future__ import annotations

from collections import deque
from collections.abc import Hashable, Iterator, Sequence
from dataclasses import dataclass
from math import prod
from typing import TYPE_CHECKING, Any, NamedTuple, cast

import networkx as nx

from sofic.algebra.transformation import (
    DEFAULT_MAX_SIZE,
    Transformation,
    TransformationSemigroup,
    _compose,
    _permutation_order,
)

if TYPE_CHECKING:
    from sofic.algebra.cascade import CascadeProduct, LevelAction

__all__ = ["EffectiveTheory", "HolonomyDecomposition", "HolonomyLevel", "holonomy_decomposition"]

Subset = frozenset[int]
Chain = tuple[Subset, ...]
Coordinates = tuple[int | None, ...]


def _set_key(subset: Subset) -> tuple[int, tuple[int, ...]]:
    return (-len(subset), tuple(sorted(subset)))


class EffectiveTheory(NamedTuple):
    """The coarse-grained machine on the top levels of a holonomy cascade.

    ``automaton`` is a DFA on coordinate prefixes, ``superstates`` maps each
    prefix to the original states it covers, and ``projection`` maps every
    full coordinate tuple to its prefix. ``distribution`` and ``lumpable``
    are filled in only when a stochastic machine is supplied.
    """

    automaton: Any
    superstates: dict[Coordinates, frozenset[Hashable]]
    projection: dict[Coordinates, Coordinates]
    distribution: dict[Coordinates, float] | None
    lumpable: bool | None


@dataclass(frozen=True)
class HolonomyLevel:
    """One level of the holonomy cascade.

    ``representatives[k]`` is a class representative of this depth,
    ``tiles[k]`` its tiles, and ``group_generators[k]`` permutations of
    ``range(len(tiles[k]))`` generating its holonomy group. The component's
    state set is ``states``: pairs ``(k, t)`` meaning tile ``t`` of
    representative ``k`` (the disjoint union of the tile sets).
    """

    depth: int
    height: int
    representatives: tuple[Subset, ...]
    tiles: tuple[tuple[Subset, ...], ...]
    group_generators: tuple[tuple[tuple[int, ...], ...], ...]
    states: tuple[tuple[int, int], ...]

    @property
    def groups(self) -> tuple[Any, ...]:
        """Holonomy groups as sympy ``PermutationGroup`` objects on tile positions."""
        from sofic.algebra._groups import permutation_group

        return tuple(
            permutation_group(gens, len(tiles)) for gens, tiles in zip(self.group_generators, self.tiles, strict=True)
        )

    @property
    def order(self) -> int:
        """Order of the level group, the direct product of its holonomy groups."""
        if self.is_trivial:
            return 1
        return prod(int(g.order()) for g in self.groups)

    @property
    def is_trivial(self) -> bool:
        return all(all(p == tuple(range(len(p))) for p in gens) for gens in self.group_generators)


class HolonomyDecomposition:
    """The holonomy decomposition of a :class:`TransformationSemigroup`.

    Attributes
    ----------
    semigroup : TransformationSemigroup
    image_set : tuple of frozenset
        The extended image set, largest sets first.
    height : dict
        Height of every set in ``image_set`` (singletons have height 0).
    levels : tuple of HolonomyLevel
        Top (depth 1) first; ``len(levels) == height[Q]``.
    """

    def __init__(self, semigroup: TransformationSemigroup) -> None:
        self.semigroup = semigroup
        n = semigroup.degree
        self._full: Subset = frozenset(range(n))
        self._gens = [(label, g) for label, g in semigroup.generators.items()]

        nodes, edges = self._orbit()
        self.image_set: tuple[Subset, ...] = tuple(sorted(nodes, key=_set_key))
        graph = nx.DiGraph()
        graph.add_nodes_from(nodes)
        for source, moves in edges.items():
            graph.add_edges_from((source, target) for _, _, target in moves)

        classes = [frozenset(c) for c in nx.strongly_connected_components(graph) if len(next(iter(c))) > 1]
        classes.sort(key=lambda c: _set_key(min(c, key=_set_key)))
        self.classes: tuple[tuple[Subset, ...], ...] = tuple(tuple(sorted(c, key=_set_key)) for c in classes)
        self.representative: dict[Subset, Subset] = {}
        for members in self.classes:
            rep = min(members, key=lambda s: tuple(sorted(s)))
            for member in members:
                self.representative[member] = rep

        self.height = self._heights(graph)
        self.n_levels = self.height[self._full]
        self.tiles = self._tiles(nodes)
        self._tile_sets = {p: frozenset(ts) for p, ts in self.tiles.items()}
        self.to_rep, self.from_rep = self._translations(edges)
        self.levels = self._levels(edges)
        self._level_index = [{state: i for i, state in enumerate(self._level_keys(level))} for level in self.levels]

    # -- construction ---------------------------------------------------------

    def _orbit(self) -> tuple[set[Subset], dict[Subset, list[tuple[Hashable, Transformation, Subset]]]]:
        singletons = {frozenset({x}) for x in range(self.semigroup.degree)}
        nodes = {self._full} | singletons
        edges: dict[Subset, list[tuple[Hashable, Transformation, Subset]]] = {}
        queue = deque(nodes)
        while queue:
            subset = queue.popleft()
            moves = []
            for label, g in self._gens:
                image = g.act(subset)
                moves.append((label, g, image))
                if image not in nodes:
                    nodes.add(image)
                    queue.append(image)
            edges[subset] = moves
        return nodes, edges

    def _heights(self, graph: nx.DiGraph) -> dict[Subset, int]:
        reps = sorted(set(self.representative.values()), key=_set_key)
        reach = {r: nx.descendants(graph, r) | {r} for r in reps}
        below = {a: [b for b in reps if b != a and any(b <= c for c in reach[a]) and len(b) > 1] for a in reps}
        heights: dict[Subset, int] = {}

        def height(rep: Subset) -> int:
            if rep not in heights:
                heights[rep] = 1 + max((height(b) for b in below[rep]), default=0)
            return heights[rep]

        result = {s: 0 for s in graph.nodes if len(s) == 1}
        for member, rep in self.representative.items():
            result[member] = height(rep)
        return result

    def _tiles(self, nodes: set[Subset]) -> dict[Subset, tuple[Subset, ...]]:
        tiles: dict[Subset, tuple[Subset, ...]] = {}
        for parent in nodes:
            if len(parent) == 1:
                continue
            proper = [s for s in nodes if s < parent]
            maximal = [s for s in proper if not any(s < t for t in proper)]
            tiles[parent] = tuple(sorted(maximal, key=_set_key))
        return tiles

    def _translations(
        self, edges: dict[Subset, list[tuple[Hashable, Transformation, Subset]]]
    ) -> tuple[dict[Subset, Transformation], dict[Subset, Transformation]]:
        """Maps ``P -> rep(P)`` and back, inverse to each other on ``P`` and ``rep(P)``."""
        n = self.semigroup.degree
        identity = tuple(range(n))
        to_rep: dict[Subset, tuple[int, ...]] = {}
        from_rep: dict[Subset, tuple[int, ...]] = {}
        incoming: dict[Subset, list[tuple[tuple[int, ...], Subset]]] = {}
        for source, moves in edges.items():
            for _, g, target in moves:
                incoming.setdefault(target, []).append((g.images, source))
        for members in self.classes:
            rep = self.representative[members[0]]
            inside = set(members)
            from_rep[rep] = identity
            queue = deque([rep])
            while queue:
                p = queue.popleft()
                for _, g, q in edges[p]:
                    if q in inside and q not in from_rep:
                        from_rep[q] = _compose(from_rep[p], g.images)
                        queue.append(q)
            to_rep[rep] = identity
            queue = deque([rep])
            while queue:
                q = queue.popleft()
                for g_images, p in incoming.get(q, []):
                    if p in inside and p not in to_rep:
                        to_rep[p] = _compose(g_images, to_rep[q])
                        queue.append(p)
            for p in members:
                roundtrip = _compose(to_rep[p], from_rep[p])
                order = _permutation_order(roundtrip, p)
                from_rep[p] = _compose(from_rep[p], Transformation(roundtrip).power(order - 1).images)
        return (
            {p: Transformation(m) for p, m in to_rep.items()},
            {p: Transformation(m) for p, m in from_rep.items()},
        )

    def _levels(self, edges: dict[Subset, list[tuple[Hashable, Transformation, Subset]]]) -> tuple[HolonomyLevel, ...]:
        by_depth: dict[int, list[Subset]] = {}
        for rep in sorted(set(self.representative.values()), key=lambda s: tuple(sorted(s))):
            by_depth.setdefault(self.depth(rep), []).append(rep)
        levels = []
        for depth in range(1, self.n_levels + 1):
            reps = tuple(by_depth.get(depth, []))
            tiles = tuple(self.tiles[r] for r in reps)
            gens = tuple(self._holonomy_generators(r, edges) for r in reps)
            states = tuple((k, t) for k, ts in enumerate(tiles) for t in range(len(ts)))
            levels.append(
                HolonomyLevel(
                    depth=depth,
                    height=self.n_levels - depth + 1,
                    representatives=reps,
                    tiles=tiles,
                    group_generators=gens,
                    states=states,
                )
            )
        return tuple(levels)

    def _holonomy_generators(
        self, rep: Subset, edges: dict[Subset, list[tuple[Hashable, Transformation, Subset]]]
    ) -> tuple[tuple[int, ...], ...]:
        tiles = self.tiles[rep]
        position = {t: i for i, t in enumerate(tiles)}
        perms: dict[tuple[int, ...], None] = {}
        for p, r in self.representative.items():
            if r != rep:
                continue
            for _, g, q in edges[p]:
                if self.representative.get(q) != rep:
                    continue
                loop = self.from_rep[p] * g * self.to_rep[q]
                perms[tuple(position[loop.act(t)] for t in tiles)] = None
        identity = tuple(range(len(tiles)))
        return tuple(p for p in perms if p != identity) or (identity,)

    @staticmethod
    def _level_keys(level: HolonomyLevel) -> Iterator[tuple[Subset, Subset]]:
        for k, t in level.states:
            yield (level.representatives[k], level.tiles[k][t])

    # -- geometry of sets -----------------------------------------------------

    def depth(self, subset: Subset) -> int:
        """Depth ``h(Q) - h(P) + 1`` of a set; singletons sit below the last level."""
        return self.n_levels - self.height[subset] + 1

    def equivalence_class(self, subset: Subset) -> tuple[Subset, ...]:
        rep = self.representative[subset]
        return next(c for c in self.classes if rep in c)

    # -- chains and coordinates -----------------------------------------------

    def lift(self, state: Hashable) -> Chain:
        """Return the canonical maximal tile chain from ``Q`` down to ``{state}``."""
        x = self.semigroup.state_index(state)
        chain = [self._full]
        while len(chain[-1]) > 1:
            chain.append(next(t for t in self.tiles[chain[-1]] if x in t))
        return tuple(chain)

    def chains(self) -> Iterator[Chain]:
        """Yield every maximal tile chain from ``Q`` to a singleton."""
        stack: list[Chain] = [(self._full,)]
        while stack:
            chain = stack.pop()
            if len(chain[-1]) == 1:
                yield chain
                continue
            for tile in reversed(self.tiles[chain[-1]]):
                stack.append((*chain, tile))

    def encode(self, chain: Sequence[Subset]) -> Coordinates:
        """Return the cascade coordinates of a maximal tile chain.

        Coordinate ``i`` is an index into ``levels[i].states`` or ``None``
        when no set of the chain sits at depth ``i + 1``.
        """
        coords: list[int | None] = [None] * self.n_levels
        for parent, tile in zip(chain, chain[1:], strict=False):
            rep = self.representative[parent]
            level = self.depth(parent) - 1
            coords[level] = self._level_index[level][(rep, self.to_rep[parent].act(tile))]
        return tuple(coords)

    def decode(self, coords: Sequence[int | None]) -> Chain:
        """Inverse of :meth:`encode`; raises ``ValueError`` on invalid coordinates."""
        if len(coords) != self.n_levels:
            raise ValueError(f"expected {self.n_levels} coordinates")
        chain = [self._full]
        for i, c in enumerate(coords):
            parent = chain[-1]
            on_level = len(parent) > 1 and self.depth(parent) == i + 1
            if c is None:
                if on_level:
                    raise ValueError(f"missing coordinate at level {i}")
                continue
            if not on_level:
                raise ValueError(f"unexpected coordinate at level {i}")
            k, t = self.levels[i].states[c]
            level = self.levels[i]
            if level.representatives[k] != self.representative[parent]:
                raise ValueError(f"coordinate at level {i} belongs to another representative")
            chain.append(self.from_rep[parent].act(level.tiles[k][t]))
        if len(chain[-1]) != 1:
            raise ValueError("coordinates do not reach a singleton")
        return tuple(chain)

    def coordinates(self, state: Hashable) -> Coordinates:
        """Return the coordinates of the canonical lift of ``state``."""
        return self.encode(self.lift(state))

    def state(self, coords: Sequence[int | None]) -> Hashable:
        """Return the original state a coordinate tuple stands for."""
        (x,) = self.decode(coords)[-1]
        return self.semigroup.states[x]

    def step(self, chain: Sequence[Subset], s: Transformation) -> Chain:
        """Lift the action of ``s`` to maximal tile chains.

        The images ``P_i · s`` of the chain form a chain of image sets; this
        returns a maximal tile chain containing all of them (a *dominating*
        chain) built top down. Below a set ``C`` it takes the first image that
        is a proper subset of ``C``: that image itself if it is a tile of
        ``C``, otherwise the first tile of ``C`` containing it. The choice down
        to ``P · s`` depends only on the chain down to ``P``, which is what
        makes the cascade's dependency functions well defined
        :cite:`EgriNagyNehaniv2015`.
        """
        images = [s.act(p) for p in chain]
        current = self._full
        result = [current]
        while len(current) > 1:
            target = next(d for d in images if d < current)
            if target in self._tile_sets[current]:
                current = target
            else:
                current = next(t for t in self.tiles[current] if target <= t)
            result.append(current)
        return tuple(result)

    def act(self, coords: Sequence[int | None], label: Hashable) -> Coordinates:
        """Apply generator ``label`` to coordinates."""
        g = self.semigroup.generators[label]
        return self.encode(self.step(self.decode(coords), g))

    def level_actions(self, chain: Sequence[Subset], s: Transformation) -> tuple[LevelAction, ...]:
        """Return the component action of ``s`` at each level for ``chain``.

        At level ``i`` let ``P`` and ``P'`` be the sets the old and new chains
        are refining there. If ``P'`` does not sit at depth ``i + 1`` the
        coordinate is cleared; if ``P · s = P'`` the action is the holonomy
        permutation ``m(R -> P) s m(P' -> R)`` of the representative's tiles;
        otherwise it is a reset to the new coordinate.
        """
        from sofic.algebra.cascade import LevelAction

        new = self.step(chain, s)
        new_coords = self.encode(new)
        old_frames = self._frames(chain)
        new_frames = self._frames(new)
        actions = []
        for i in range(self.n_levels):
            p, q = old_frames[i], new_frames[i]
            if len(q) == 1 or self.depth(q) != i + 1:
                actions.append(LevelAction.constant(None))
            elif s.act(p) == q:
                rep = self.representative[q]
                loop = self.from_rep[p] * s * self.to_rep[q]
                level = self.levels[i]
                k = level.representatives.index(rep)
                index = self._level_index[i]
                mapping = {index[(rep, tile)]: index[(rep, loop.act(tile))] for tile in level.tiles[k]}
                actions.append(LevelAction.permutation(mapping))
            else:
                actions.append(LevelAction.constant(new_coords[i]))
        return tuple(actions)

    def _frames(self, chain: Sequence[Subset]) -> list[Subset]:
        """``frames[i]`` is the deepest set of ``chain`` placed above level ``i``."""
        frames = []
        current = self._full
        members = iter(chain[1:])
        nxt = next(members, None)
        for i in range(self.n_levels):
            frames.append(current)
            if len(current) > 1 and self.depth(current) == i + 1 and nxt is not None:
                current = nxt
                nxt = next(members, None)
        return frames

    # -- outputs --------------------------------------------------------------

    def to_cascade(self, *, max_states: int = DEFAULT_MAX_SIZE) -> CascadeProduct:
        """Return the holonomy cascade product with explicit dependency functions."""
        from sofic.algebra.cascade import build_holonomy_cascade

        return build_holonomy_cascade(self, max_states=max_states)

    def effective_theory(self, k: int, *, machine: Any = None, max_states: int = DEFAULT_MAX_SIZE) -> EffectiveTheory:
        """Return the automaton on the top ``k`` levels of the holonomy cascade.

        Truncating the cascade gives a coarse-grained machine whose states
        are *superstates*: sets of original states that agree on the top
        ``k`` coordinates of some lift. Superstates may overlap. This is the
        "effective theory" of :cite:`DeDeo2011`.

        With a stochastic ``machine`` (whose transition semigroup is this
        decomposition's), states are grouped by the prefix of their canonical
        lift. The result reports the stationary mass of each group and
        whether that partition is strongly lumpable (see
        :func:`~sofic.generators.lumping.is_lumpable`), that is, whether the
        coarse-grained process is itself Markov on the superstates.
        """
        full = self.to_cascade(max_states=max_states)
        cascade = full.truncate(k)
        automaton = cascade.as_dfa()
        projection = {coords: coords[:k] for coords in full.decoding}
        distribution = lumpable = None
        if machine is not None:
            from sofic.generators.lumping import is_lumpable

            index = machine.reindex()
            pi = machine.stationary_distribution()
            partition = {index.state(i): self.coordinates(index.state(i))[:k] for i in range(len(index))}
            distribution = {}
            for i in range(len(index)):
                key = partition[index.state(i)]
                distribution[key] = distribution.get(key, 0.0) + float(pi[i])
            lumpable = is_lumpable(machine, partition)
        superstates = {prefix: cast("frozenset[Hashable]", states) for prefix, states in cascade.decoding.items()}
        return EffectiveTheory(automaton, superstates, projection, distribution, lumpable)

    def describe(self) -> str:
        """Human-readable summary: one line per level with representatives and groups."""
        labels = self.semigroup.states

        def show(subset: Subset) -> str:
            return "{" + ", ".join(str(labels[x]) for x in sorted(subset)) + "}"

        lines = [f"holonomy decomposition: {len(self.image_set)} image sets, {self.n_levels} levels"]
        for level in self.levels:
            parts = []
            for rep, tiles, group in zip(level.representatives, level.tiles, level.groups, strict=True):
                parts.append(f"{show(rep)} [{len(tiles)} tiles, |H|={group.order()}]")
            lines.append(f"  depth {level.depth}: " + "; ".join(parts))
        return "\n".join(lines)


def holonomy_decomposition(machine: Any, **kwargs: Any) -> HolonomyDecomposition:
    """Return the holonomy decomposition of a semigroup or deterministic machine.

    ``machine`` is anything :func:`~sofic.algebra.adapters.transformation_semigroup`
    accepts; keyword arguments are passed through to it.

    Examples
    --------
    >>> from sofic.algebra import TransformationSemigroup
    >>> hd = holonomy_decomposition(TransformationSemigroup({"t": (1, 0, 2), "c": (0, 1, 1)}))
    >>> [level.order for level in hd.levels]
    [1, 2]
    """
    from sofic.algebra.adapters import transformation_semigroup

    return HolonomyDecomposition(transformation_semigroup(machine, **kwargs))
