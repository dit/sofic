"""Permutation-group helpers backed by :mod:`sympy.combinatorics` (optional)."""

from __future__ import annotations

from collections.abc import Iterable
from typing import Any


def require_sympy() -> Any:
    try:
        import sympy.combinatorics as combinatorics
    except ImportError as exc:  # pragma: no cover - exercised only without sympy
        raise ImportError(
            "group-theoretic parts of sofic.algebra need sympy; install with `pip install sofic[symbolic]`"
        ) from exc
    return combinatorics


def permutation_group(perms: Iterable[tuple[int, ...]], degree: int) -> Any:
    """Return the sympy ``PermutationGroup`` generated by ``perms`` on ``degree`` points.

    Generators already in the group so far are skipped, so a large redundant
    generating set (for example every element of a subgroup) collapses to at
    most ``log2 |G|`` generators.
    """
    combinatorics = require_sympy()
    permutation = combinatorics.Permutation
    identity = permutation(list(range(degree)), size=degree)
    gens: list[Any] = []
    group = combinatorics.PermutationGroup([identity])
    for perm in dict.fromkeys(perms):
        p = permutation(list(perm), size=degree)
        if p.is_Identity or group.contains(p):
            continue
        gens.append(p)
        group = combinatorics.PermutationGroup(gens)
    return group


def composition_factor_orders(group: Any) -> list[int]:
    """Orders of the Jordan-Hölder composition factors, ascending, with multiplicity.

    Solvable groups have cyclic factors of prime order, read off the order.
    Otherwise abelian layers of the derived series are peeled off; a perfect
    group is simple iff every nontrivial conjugacy class has normal closure
    the whole group, and else splits through a proper normal subgroup and
    the quotient (built as the action on cosets).
    """
    order = int(group.order())
    if order == 1:
        return []
    if group.is_solvable:
        return _prime_factors(order)
    derived = group.derived_subgroup()
    if derived.order() < order:
        return sorted(_prime_factors(order // int(derived.order())) + composition_factor_orders(derived))
    normal = _proper_normal_subgroup(group)
    if normal is None:
        return [order]
    return sorted(composition_factor_orders(normal) + composition_factor_orders(_quotient(group, normal)))


def _prime_factors(n: int) -> list[int]:
    factors = []
    p = 2
    while p * p <= n:
        while n % p == 0:
            factors.append(p)
            n //= p
        p += 1
    if n > 1:
        factors.append(n)
    return factors


def _proper_normal_subgroup(group: Any) -> Any:
    order = group.order()
    for cls in group.conjugacy_classes():
        x = next(iter(cls))
        if x.is_Identity:
            continue
        closure = group.normal_closure(x)
        if closure.order() < order:
            return closure
    return None


def _quotient(group: Any, normal: Any) -> Any:
    """``G / N`` as the permutation group of ``G`` acting on the right cosets of ``N``."""
    combinatorics = require_sympy()
    reps = [group.identity]

    def coset(y: Any) -> int:
        for i, r in enumerate(reps):
            if normal.contains(y * ~r):
                return i
        reps.append(y)
        return len(reps) - 1

    images: dict[int, list[int]] = {}
    i = 0
    while i < len(reps):
        for k, g in enumerate(group.generators):
            images.setdefault(k, []).append(coset(reps[i] * g))
        i += 1
    degree = len(reps)
    return combinatorics.PermutationGroup(
        [combinatorics.Permutation(images[k], size=degree) for k in range(len(group.generators))]
    )
